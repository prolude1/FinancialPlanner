const assert = require('node:assert/strict');
(async () => {
  const {collectResearchHoldings, createHoldingsResearchPanel} = await import('../web/features/stocks/holdings-research.js');
  const {financialTrendRows, createFinancialTrendPanel} = await import('../web/features/stocks/financial-trends.js');
  const {createResearchWatchlist} = await import('../web/features/stocks/research-watchlist.js');
  const esc = value => String(value ?? '').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
  const accounts = [{id:'one',name:'<Broker>',type:'brokerage',holdings:[{exchange:'NASDAQ',symbol:'ABC',quantity:'1',asset_class:'equity'}]},
    {id:'two',name:'Second',type:'brokerage',holdings:[{exchange:'NASDAQ',symbol:'ABC',quantity:'2'}, {exchange:'SGX',symbol:'ABC',quantity:'3'}, {exchange:'NASDAQ',symbol:'OLD',quantity:'0'}]}];
  const holdings = collectResearchHoldings(accounts);
  assert.equal(holdings.length, 2);
  assert.equal(holdings[0].accounts.length, 2);
  const panel = createHoldingsResearchPanel({esc})(accounts, 'NASDAQ:ABC');
  assert(panel.includes('#stocks/NASDAQ%3AABC'));
  assert(panel.includes('aria-current="page"'));
  assert(panel.includes('&lt;Broker&gt;'));
  assert(!panel.includes('OLD'));
  const quarters = [{period_end:'2025-09-30',revenue:'200',profit_after_tax:'-20',free_cash_flow:'0'},
    {period_end:'2025-03-31',revenue:'100',profit_after_tax:'20',free_cash_flow:null}];
  const rows = financialTrendRows(quarters);
  assert.equal(rows[0].profit_margin, 20);
  assert.equal(rows[1].profit_margin, -10);
  assert.equal(financialTrendRows([{period_end:'2025-01-01',revenue:'0',profit_after_tax:'2'}])[0].profit_margin, null);
  const trends = createFinancialTrendPanel({esc});
  const html = trends({supported:true,quarters,currency:'USD'});
  assert(html.includes('Quarterly financial trends'));
  assert(html.includes('Profit margin'));
  assert(!html.includes('NaN'));
  const paths = [...html.matchAll(/class="trend-line" d="([^"]*)"/g)];
  assert(!paths[0][1].includes('L'), 'Missing quarter must break the line');
  const annual = trends({supported:true},{fiscal_years:[{period_end:'2024-12-31',revenue:'100'}, {period_end:'2025-12-31',revenue:'120'}],currency:'EUR'},'annual');
  assert(annual.includes('Annual financial trends'));
  assert(annual.includes('EUR'));
  assert(annual.match(/class="trend-line" d="[^"]*L/));
  assert.equal(trends({supported:false},null), '');
  assert(trends({supported:true,quarters:[]}).includes('No quarterly statements'));

  let updates = 0;
  const pending = [];
  const watchlist = createResearchWatchlist({esc,onUpdate:()=>updates++,api:(path,options)=>new Promise((resolve,reject)=>pending.push({path,options,resolve,reject}))});
  watchlist.panel('NASDAQ:AAPL');
  await Promise.resolve();
  pending.shift().resolve({security_ids:[]});
  await new Promise(resolve=>setImmediate(resolve));
  assert(watchlist.panel('NASDAQ:AAPL').includes('Add to watchlist'));
  const mutation = watchlist.update('NASDAQ:AAPL');
  const request = pending.shift();
  assert.equal(request.options.method, 'PUT');
  request.resolve({security_ids:['NASDAQ:AAPL']});
  await mutation;
  assert(watchlist.panel('NASDAQ:AAPL').includes('Remove from watchlist'));
  const staleMutation = watchlist.update('NASDAQ:OLD');
  watchlist.invalidate();
  pending.shift().resolve({security_ids:['NASDAQ:OLD']});
  await staleMutation;
  const afterReset = watchlist.panel('');
  assert(!afterReset.includes('NASDAQ:OLD'));
  await Promise.resolve();
  pending.shift().reject(new Error('Offline'));
  await new Promise(resolve=>setImmediate(resolve));
  assert(watchlist.panel('').includes('Offline'));
  assert(updates > 0);
  console.log('PASS: holdings research, quarterly/annual trends, and watchlist state');
})().catch(error => {console.error(error);process.exitCode=1;});
